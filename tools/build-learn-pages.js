#!/usr/bin/env node
/* tools/build-learn-pages.js — builds the static /learn/ pages.
 *
 *   data/learn-content.md   the approved words: era intros, teacher notes, card
 *                           blurbs, key facts, related cards, titles, descriptions
 *   js/cards.js             the game's card data: name, art, cost, IP, type, ability
 *
 * Writes (commit all of these):
 *   learn/index.html, learn/<era>/index.html, learn/<era>/<card>/index.html
 *   images/learn/thumbs/card-<id>.jpg   200px-wide grid thumbnails
 *   images/learn/art/card-<id>.jpg      400px-wide card art for card pages
 *   sitemap.xml                         its /learn/ entries (other entries kept)
 *
 *   node tools/build-learn-pages.js            build (makes any missing images)
 *   node tools/build-learn-pages.js --images   also remake every image (after new card art)
 *   node tools/build-learn-pages.js --check    change nothing; exit 1 if anything is stale
 *
 * Images are resized with macOS `sips`. The game itself is untouched: these pages
 * read the same card data, so a changed cost, ability or name shows up on the
 * next build, and test/learn-pages.test.js fails until it's rebuilt.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://playshouldersofgiants.com';
const CONTENT = 'data/learn-content.md';
const THUMB_W = 200, ART_W = 400;   // shown at most ~150px / 240px wide
const QUALITY = { [THUMB_W]: 60, [ART_W]: 65 };   // card art is grainy; higher quality barely helps
const BANNER = '<!-- Generated by tools/build-learn-pages.js from data/learn-content.md and js/cards.js. Edit those and rebuild; don\'t edit this file. -->';

/* ── Inputs ─────────────────────────────────────────────────────────────── */

function loadCards() {
  const src = fs.readFileSync(path.join(ROOT, 'js/cards.js'), 'utf8');
  return new Function('window', src + '\n;return typeof CARDS !== "undefined" ? CARDS : window.CARDS;')({});
}

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const reEsc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
// Inline Markdown used in the content: **bold** and *italic*. Escaped first.
const inline = (s) => esc(s).replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>').replace(/\*([^*]+)\*/g, '<em>$1</em>');

// `- **Key (n):** value` bullets at the top of a section.
function fields(sec) {
  const out = {};
  for (const m of sec.matchAll(/^- \*\*([^*(]+?)(?: \(\d+\))?:\*\* (.*)$/gm)) out[m[1].trim()] = m[2].trim();
  return out;
}
// A `**Label:**` line, a blank line, then text up to the next label or `---`.
function block(sec, label) {
  const m = sec.match(new RegExp('^\\*\\*' + reEsc(label) + ':\\*\\*[ \\t]*\\n\\n?([\\s\\S]*?)(?=\\n\\*\\*[^*\\n]+:\\*\\*|\\n---|(?![\\s\\S]))', 'm'));
  return m ? m[1].trim() : '';
}
// Paragraphs and `- ` lists → HTML. A list may follow its paragraph with no
// blank line between ("This unit covers:" then "- the Nile …").
function blocksToHtml(text, listClass) {
  const out = [];
  for (const chunk of text.split(/\n\s*\n/)) {
    let para = [], items = [];
    const flushPara = () => { if (para.length) out.push('<p>' + inline(para.join(' ')) + '</p>'); para = []; };
    const flushList = () => { if (items.length) out.push('<ul class="' + (listClass || 'gems') + '">' + items.map((l) => '<li>' + inline(l) + '</li>').join('') + '</ul>'); items = []; };
    for (const line of chunk.trim().split('\n')) {
      if (/^- /.test(line)) { flushPara(); items.push(line.slice(2)); } else { flushList(); para.push(line.trim()); }
    }
    flushPara(); flushList();
  }
  return out.join('\n');
}
const plain = (s) => s.replace(/\*\*?([^*]+)\*\*?/g, '$1');
const ids = (s) => (s || '').split(',').map((x) => parseInt(x, 10)).filter((n) => !isNaN(n));

function parseContent() {
  const md = fs.readFileSync(path.join(ROOT, CONTENT), 'utf8');
  const updated = (md.match(/^- \*\*Updated:\*\* (\d{4}-\d{2}-\d{2})$/m) || [])[1];
  if (!updated) throw new Error(CONTENT + ': missing "- **Updated:** YYYY-MM-DD"');
  const secs = md.split(/^## /m).slice(1);
  const out = { updated, index: null, eras: [], cards: [] };
  for (const sec of secs) {
    const head = sec.split('\n')[0].trim();
    const f = fields(sec);
    if (head.startsWith('/learn/')) {
      out.index = { url: f.URL, title: f.Title, desc: f['Meta description'], intro: f.Intro };
    } else if (head.startsWith('Era: ')) {
      out.eras.push({
        name: head.slice(5), url: f.URL, slug: f.URL.split('/')[2], title: f.Title, desc: f['Meta description'],
        standard: f['Standards line'], earnable: ids(f['Earnable cards']),
        intro: block(sec, 'Intro (for students)'), teachers: block(sec, 'For teachers')
      });
    } else if (head.startsWith('Card: ')) {
      const parts = f.URL.split('/');
      out.cards.push({
        name: head.slice(6), url: f.URL, era: parts[2], slug: parts[3], id: parseInt(f['Card id'], 10),
        title: f.Title, desc: f['Meta description'], earn: f['How students earn it'],
        blurb: block(sec, 'Blurb'), facts: block(sec, 'Key facts'),
        related: ((sec.match(/^\*\*Related cards:\*\* (.*)$/m) || [])[1] || '').split(',').map((s) => s.trim()).filter(Boolean)
      });
    }
  }
  return out;
}

/* ── Images ─────────────────────────────────────────────────────────────── */

function jpegSize(file) {
  const b = fs.readFileSync(file);
  for (let i = 2; i < b.length;) {
    if (b[i] !== 0xff) { i++; continue; }
    const marker = b[i + 1], len = b.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
      return { h: b.readUInt16BE(i + 5), w: b.readUInt16BE(i + 7) };
    }
    i += 2 + len;
  }
  throw new Error('not a JPEG: ' + file);
}
const thumbPath = (id) => 'images/learn/thumbs/card-' + id + '.jpg';
const artPath = (id) => 'images/learn/art/card-' + id + '.jpg';

function makeImage(src, dest, width) {
  fs.mkdirSync(path.dirname(path.join(ROOT, dest)), { recursive: true });
  execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', String(QUALITY[width] || 65), '--resampleWidth', String(width),
    path.join(ROOT, src), '--out', path.join(ROOT, dest)], { stdio: 'ignore' });
}

/* ── Page pieces ────────────────────────────────────────────────────────── */

function jsonLd(obj) {
  return '<script type="application/ld+json">' + JSON.stringify(obj).replace(/</g, '\\u003c') + '</script>';
}
